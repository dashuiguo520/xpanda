CREATE TABLE IF NOT EXISTS `autoplay_config` (
  `char_id` INT UNSIGNED NOT NULL,
  `revision` INT UNSIGNED NOT NULL DEFAULT 0,
  `search_range` SMALLINT UNSIGNED NOT NULL DEFAULT 12,
  `normal_attack` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `autoloot_rate` SMALLINT UNSIGNED NOT NULL DEFAULT 10000,
  `autoloot_types` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `sit_recovery` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `sit_hp_below` TINYINT UNSIGNED NOT NULL DEFAULT 30,
  `sit_sp_below` TINYINT UNSIGNED NOT NULL DEFAULT 20,
  `hp_recover_below` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  `sp_recover_below` TINYINT UNSIGNED NOT NULL DEFAULT 20,
  `emergency_hp_below` TINYINT UNSIGNED NOT NULL DEFAULT 15,
  `teleport_skill_id` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `teleport_item_id` INT UNSIGNED NOT NULL DEFAULT 0,
  `teleport_min_interval` INT UNSIGNED NOT NULL DEFAULT 10000,
  `no_monster_teleport_seconds` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `surrounded_teleport_count` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `mode` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `boss_action` TINYINT UNSIGNED NOT NULL DEFAULT 2,
  `miss_teleport` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `storage_weight_at` TINYINT UNSIGNED NOT NULL DEFAULT 70,
  `death_action` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `follow_char_id` INT UNSIGNED NOT NULL DEFAULT 0,
  `follow_distance` SMALLINT UNSIGNED NOT NULL DEFAULT 3,
  `follow_attack` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `auto_accept_party` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `follow_offline_action` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `inventory_stop_at` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`char_id`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `autoplay_skill` (
  `char_id` INT UNSIGNED NOT NULL,
  `slot` TINYINT UNSIGNED NOT NULL,
  `skill_id` SMALLINT UNSIGNED NOT NULL,
  `skill_lv` SMALLINT UNSIGNED NOT NULL,
  `enabled` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `target_type` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `hp_min` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `hp_max` TINYINT UNSIGNED NOT NULL DEFAULT 100,
  PRIMARY KEY (`char_id`,`slot`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `autoplay_recovery_item` (
  `char_id` INT UNSIGNED NOT NULL,
  `slot` TINYINT UNSIGNED NOT NULL,
  `item_id` INT UNSIGNED NOT NULL,
  `enabled` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `resource_type` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `trigger_below` TINYINT UNSIGNED NOT NULL DEFAULT 50,
  PRIMARY KEY (`char_id`,`slot`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `autoplay_discard_item` (
  `char_id` INT UNSIGNED NOT NULL,
  `slot` TINYINT UNSIGNED NOT NULL,
  `item_id` INT UNSIGNED NOT NULL,
  `keep_amount` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`char_id`,`slot`)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `autoplay_loot_item` (
  `char_id` INT UNSIGNED NOT NULL,
  `slot` TINYINT UNSIGNED NOT NULL,
  `item_id` INT UNSIGNED NOT NULL,
  PRIMARY KEY (`char_id`,`slot`)
) ENGINE=InnoDB;
